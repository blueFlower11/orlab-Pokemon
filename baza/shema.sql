-- Normalizirana PostgreSQL shema za izmišljena bića.
-- Svi objekti nalaze se u zasebnoj shemi kako ne bi mijenjali druge tablice.

CREATE SCHEMA IF NOT EXISTS lab_bica;

CREATE TABLE IF NOT EXISTS lab_bica.staniste (
    staniste_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS lab_bica.rijetkost (
    rijetkost_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS lab_bica.tip_bica (
    tip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS lab_bica.sposobnost (
    sposobnost_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS lab_bica.vrsta_bica (
    bice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kataloski_broj INTEGER NOT NULL UNIQUE CHECK (kataloski_broj > 0),
    naziv VARCHAR(100) NOT NULL UNIQUE,
    opis TEXT NOT NULL,
    visina_cm NUMERIC(6, 1) NOT NULL CHECK (visina_cm > 0),
    masa_kg NUMERIC(7, 2) NOT NULL CHECK (masa_kg > 0),
    staniste_id BIGINT NOT NULL REFERENCES lab_bica.staniste (staniste_id) ON DELETE RESTRICT,
    rijetkost_id BIGINT NOT NULL REFERENCES lab_bica.rijetkost (rijetkost_id) ON DELETE RESTRICT
);

-- Statistike su u zasebnoj tablici jer čine jednu grupu atributa po biću.
CREATE TABLE IF NOT EXISTS lab_bica.osnovna_statistika (
    bice_id BIGINT PRIMARY KEY REFERENCES lab_bica.vrsta_bica (bice_id) ON DELETE CASCADE,
    zdravlje SMALLINT NOT NULL CHECK (zdravlje BETWEEN 1 AND 255),
    napad SMALLINT NOT NULL CHECK (napad BETWEEN 1 AND 255),
    obrana SMALLINT NOT NULL CHECK (obrana BETWEEN 1 AND 255),
    specijalni_napad SMALLINT NOT NULL CHECK (specijalni_napad BETWEEN 1 AND 255),
    specijalna_obrana SMALLINT NOT NULL CHECK (specijalna_obrana BETWEEN 1 AND 255),
    brzina SMALLINT NOT NULL CHECK (brzina BETWEEN 1 AND 255)
);

-- Veza više-prema-više između bića i njihovih tipova.
CREATE TABLE IF NOT EXISTS lab_bica.bice_tip (
    bice_id BIGINT NOT NULL REFERENCES lab_bica.vrsta_bica (bice_id) ON DELETE CASCADE,
    tip_id BIGINT NOT NULL REFERENCES lab_bica.tip_bica (tip_id) ON DELETE RESTRICT,
    redni_broj SMALLINT NOT NULL CHECK (redni_broj IN (1, 2)),
    PRIMARY KEY (bice_id, redni_broj),
    UNIQUE (bice_id, tip_id)
);

-- Veza više-prema-više između bića i sposobnosti.
CREATE TABLE IF NOT EXISTS lab_bica.bice_sposobnost (
    bice_id BIGINT NOT NULL REFERENCES lab_bica.vrsta_bica (bice_id) ON DELETE CASCADE,
    sposobnost_id BIGINT NOT NULL REFERENCES lab_bica.sposobnost (sposobnost_id) ON DELETE RESTRICT,
    utor SMALLINT NOT NULL CHECK (utor > 0),
    skrivena BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (bice_id, sposobnost_id),
    UNIQUE (bice_id, utor)
);

CREATE TABLE IF NOT EXISTS lab_bica.nacin_razvoja (
    nacin_razvoja_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS lab_bica.vrsta_uvjeta_razvoja (
    vrsta_uvjeta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv VARCHAR(60) NOT NULL UNIQUE
);

-- Svaki redak predstavlja usmjeren odnos roditelj–dijete.
CREATE TABLE IF NOT EXISTS lab_bica.razvoj (
    razvoj_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roditelj_id BIGINT NOT NULL REFERENCES lab_bica.vrsta_bica (bice_id) ON DELETE CASCADE,
    dijete_id BIGINT NOT NULL REFERENCES lab_bica.vrsta_bica (bice_id) ON DELETE CASCADE,
    nacin_razvoja_id BIGINT NOT NULL REFERENCES lab_bica.nacin_razvoja (nacin_razvoja_id) ON DELETE RESTRICT,
    UNIQUE (roditelj_id, dijete_id),
    CHECK (roditelj_id <> dijete_id)
);

-- Uvjeti razvoja izdvojeni su u zasebnu tablicu; razvoj može imati više uvjeta.
CREATE TABLE IF NOT EXISTS lab_bica.uvjet_razvoja (
    razvoj_id BIGINT NOT NULL REFERENCES lab_bica.razvoj (razvoj_id) ON DELETE CASCADE,
    vrsta_uvjeta_id BIGINT NOT NULL REFERENCES lab_bica.vrsta_uvjeta_razvoja (vrsta_uvjeta_id) ON DELETE RESTRICT,
    vrijednost VARCHAR(200) NOT NULL,
    PRIMARY KEY (razvoj_id, vrsta_uvjeta_id)
);

CREATE INDEX IF NOT EXISTS bice_tip_tip_idx ON lab_bica.bice_tip (tip_id);
CREATE INDEX IF NOT EXISTS bice_sposobnost_sposobnost_idx ON lab_bica.bice_sposobnost (sposobnost_id);
CREATE INDEX IF NOT EXISTS razvoj_dijete_idx ON lab_bica.razvoj (dijete_id);
